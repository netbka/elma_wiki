import crypto from 'node:crypto';
import { actorIdentity } from './actors.mjs';

// AR-05 (#11): optional supported edits inside the snapshot -> reviewed change ->
// immutable candidate lifecycle. Only the verified widget/form script contract
// (developer-workspace.md) can produce an edit. The pinned original archive is
// never modified; generated sources/runtime are a separate artifact. A physical
// native package from an edit requires native materialization (#60/P8), which is
// unavailable, so an edited candidate is never deliverable or handed off.
export const SUPPORTED_EDIT_POLICY = 'widget-script-edit-v1';
export const EDIT_MATERIALIZATION = 'unavailable';
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
const fail = (message, statusCode = 400) => { throw Object.assign(Error(message), { statusCode }); };
const lines = text => text === '' ? [] : text.split(/\r?\n/);
const archiveFile = origin => origin.split('#')[0];

// Line-multiset counts are a review aid only; the hashes cover every byte.
function lineDelta(before, after) {
  const counts = new Map();
  for (const line of lines(before)) counts.set(line, (counts.get(line) || 0) + 1);
  let added = 0;
  for (const line of lines(after)) { const left = counts.get(line) || 0; if (left) counts.set(line, left - 1); else added++; }
  return { added, removed: [...counts.values()].reduce((sum, n) => sum + n, 0) };
}

// Binds a workspace generation result to the exact pinned release snapshot.
export function captureSupportedEdit(generated, { source, actor, at, id = crypto.randomUUID() }) {
  if (!actor) fail('An authenticated actor is required', 401);
  if (generated.sourceChecksum !== source.checksum) fail('Рабочая копия основана на другом снимке. Правка не может войти в этот релиз.', 409);
  const inventory = new Set(source.inventory.map(row => row.path));
  const origins = Object.values(generated.origins).map(archiveFile);
  if (!inventory.has(generated.object.archivePath) || origins.some(path => !inventory.has(path))) fail('Исходники правки отсутствуют в закреплённом снимке', 409);
  const artifact = { schemaVersion: 1, policy: SUPPORTED_EDIT_POLICY, id, baseChecksum: source.checksum, object: generated.object,
    workspaceRevision: generated.revision, origins: generated.origins, original: generated.original, files: generated.files,
    runtime: generated.runtime, toolVersion: generated.toolVersion, check: generated.check, compilerProfile: generated.compilerProfile };
  const bytes = Buffer.from(JSON.stringify(artifact));
  const profile = generated.compilerProfile;
  const edit = { id, policy: SUPPORTED_EDIT_POLICY, archivePath: generated.object.archivePath, objectId: generated.object.id,
    name: generated.object.name, kind: generated.object.kind, baseChecksum: source.checksum, workspaceRevision: generated.revision,
    files: Object.keys(generated.files).sort().map(name => ({ name, origin: generated.origins[name],
      originalSha256: hash(generated.original[name]), editedSha256: hash(generated.files[name]),
      ...lineDelta(generated.original[name], generated.files[name]) })),
    generated: { file: `edits/${id}.json`, sha256: hash(bytes), bytes: bytes.length },
    compiler: { profileHash: profile.profileHash, compilerContract: profile.compilerContract, platformVersion: profile.platformVersion,
      typescriptVersion: profile.typescriptVersion, evidenceReference: profile.evidence?.reference || null, checkedAt: generated.check.checkedAt },
    materialization: EDIT_MATERIALIZATION, actor: actorIdentity(actor), at, review: null };
  return { edit, bytes };
}

// Original files whose candidate bytes an edit replaces: their earlier reviews
// were bound to different inputs and are invalidated.
export const editedArchivePaths = edit => [...new Set([edit.archivePath, ...edit.files.map(file => archiveFile(file.origin))])];

export function reviewSupportedEdit(edit, input, actor, at, text) {
  if (!['accepted', 'rejected'].includes(input.decision)) fail('Неизвестное решение');
  return { ...edit, review: { decision: input.decision, reason: text(input.reason, 'причину решения по правке', 4000), actor: actorIdentity(actor),
    at, sha256: edit.generated.sha256, independent: actorIdentity(actor).id !== edit.actor.id } };
}

// Status is recomputed on every read/gate and never persisted: the pinned base,
// generated bytes and current compiler profile must still match the evidence.
export async function supportedEditStatus(edit, { source, generatedBytes, workspaceView }) {
  let bytes;
  try { bytes = await generatedBytes(); } catch { return { status: 'corrupt', reason: 'Сгенерированный артефакт правки отсутствует' }; }
  if (hash(bytes) !== edit.generated.sha256) return { status: 'corrupt', reason: 'Контрольная сумма артефакта правки не совпадает' };
  if (edit.baseChecksum !== source.checksum) return { status: 'stale', reason: 'Изменился базовый снимок' };
  let view;
  try { view = await workspaceView(); }
  catch (error) { if ([404, 409, 422].includes(error.status ?? error.statusCode) || /не найден/.test(error.message)) return { status: 'stale', reason: 'Рабочая копия больше не основана на закреплённом снимке' }; throw error; }
  if (view.sourceChecksum !== source.checksum) return { status: 'stale', reason: 'Рабочая копия больше не основана на закреплённом снимке' };
  if (view.compilerProfile?.profileHash !== edit.compiler.profileHash) return { status: 'stale', reason: 'Профиль ELMA compiler изменился или недоступен' };
  return { status: 'current', reason: null };
}

// The candidate identity covers the exact original and every reviewed generated artifact.
export function editedCandidate(source, edits, { id = crypto.randomUUID(), at }) {
  const manifest = { schemaVersion: 1, policy: SUPPORTED_EDIT_POLICY, originalSha256: source.checksum,
    edits: edits.map(edit => ({ id: edit.id, archivePath: edit.archivePath, sha256: edit.generated.sha256 })).sort((a, b) => a.archivePath.localeCompare(b.archivePath)) };
  return { id, sha256: hash(JSON.stringify(manifest)), createdAt: at, provenance: 'supported-edit', originalSha256: source.checksum,
    edits: manifest.edits, deployable: false, materialization: EDIT_MATERIALIZATION };
}

export function assertUneditedCandidate(candidate) {
  if (candidate?.provenance === 'supported-edit')
    fail('Кандидат с правками нельзя передать или доставить: нативная сборка изменённого пакета недоступна (#60/P8)', 409);
}
